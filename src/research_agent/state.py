GeneralResearchDomain = Literal[
    "technology_and_computer_science",  # Software, AI, cybersecurity, robotics
    "healthcare_and_medicine",          # Clinical trials, public health, nursing
    "social_sciences",                  # Psychology, education, sociology, policy
    "business_and_management",          # Economics, supply chain, HR, marketing
    "natural_and_physical_sciences",    # Physics, chemistry, environmental science
    "humanities_and_arts"               # History, literature, philosophy, design
]

class PICOCQuestion(TypedDict):
    population: list[str]
    intervention: list[str]
    comparison: list[str]
    outcome: list[str]
    context: list[str]


class FormulatedQuestion(TypedDict):
    domain: GeneralResearchDomain
    review_type: Literal['systematic', 'narrative', 'scoping', 'rapid', 'umbrella']
    framework: Literal['PICO', 'PICOC', 'PCC']
    question: PICOCQuestion


class BaseState(TypedDict):
    messages: Annotated[list[AnyMessage], operator.add]
    llm_call: Annotated[int, operator.add]
    formulated_question: FormulatedQuestion


# TODO: this is an internal state and should be moved to question formulation code.
class QuestionFormulationState(BaseState, total=False):
    user_clarification_count: int
    needs_clarification: bool
    clarification_question: str
    formulated_question: FormulatedQuestion


# Query expansion states
class Concept(BaseModel):
    name: str = Field(description="Name of the dimension, like population, context, comparison, etc, in PICOC framework.")
    value: list[str] = Field(description="The value of the dimension as mentioned in the Formulated Question.")
    synonyms: list[str] = Field(description="Synonyms for the dimension concept as used in the popular literature.")


class Query(BaseModel):
    database: Literal["arXiv", "openalex", "semantic_scholar"]
    search_strings: list[str] = Field(description="Final searchable string formatted as per the database type.")


class ExpandedQuery(BaseModel):
    framework: Literal['PICO', 'PICOC', 'PCC'] = Field(description="Name of the framework chosen to formulate the research question.")
    concepts: list[Concept]
    queries: list[Query]

class QueryExpansionState(BaseState):
    formulated_question: FormulatedQuestion
    expanded_queries: ExpandedQuery



class RetrieverState(QueryExpansionState):
    retrievals: ListRetrievals = []
    filtered_retrievals: ListRetrievals
    deduplicated_retrievals: ListRetrievals

class EvidenceSynthesisState(RetrieverState):
    paper_profiles: list[PaperProfile]
    trends: TrendAnalysis |  None
    gaps: GapAnalysis | None
    contradictions: ContradictionAnalysis | None

